// Detect browser language, default to zh
const savedLocale = localStorage.getItem('zephyr_locale')
const browserLang = navigator.language?.startsWith('zh') ? 'zh' : 'en'
const locale = ref(savedLocale || browserLang)

export function useI18n() {
  function t(key, params = {}) {
    let text = messages[locale.value]?.[key] || messages.en[key] || key
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, v)
    }
    return text
  }

  // Translate an API error response to localized text.
  // Backend returns snake_case error keys, frontend looks up "error." + key.
  function te(error, fallbackKey) {
    const key = error?.response?.data?.error
    if (key) {
      const i18nKey = 'error.' + key
      const translated = messages[locale.value]?.[i18nKey] || messages.en?.[i18nKey]
      if (translated) return translated
      if (import.meta.env.DEV) {
        console.warn(`[i18n] missing translation for "${i18nKey}"`)
      }
      // Fallback: snake_case → readable text (e.g. "upload_storage_failed" → "Upload storage failed")
      return key.replace(/_/g, ' ').replace(/^./, c => c.toUpperCase())
    }
    return fallbackKey ? t(fallbackKey) : (error?.message || '')
  }

  function setLocale(lang) {
    locale.value = lang
    localStorage.setItem('zephyr_locale', lang)
  }

  const currentLocale = computed(() => locale.value)

  return { t, te, locale: currentLocale, setLocale }
}
